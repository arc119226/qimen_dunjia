const isMain = import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
    const dir = process.argv[2] || process.env.QIMEN_CORPUS || 'C:/gitcode/doc';
    const results = verifyAllCitations(dir);
    const tally = {};
    for (const r of results) {
        tally[r.狀態] = (tally[r.狀態] || 0) + 1;
        const mark = { 相符: '✓', '相符（有校記）': '✓', 不符: '✗',
                       略過: '－', 無語料: '?', 失敗: '✗' }[r.狀態];
        console.log(`  ${mark} ${r.key.padEnd(18)} ${r.狀態}　${r.說明}`);
        if (r.未命中) for (const m of r.未命中) console.log(`        未命中：${m}…`);
    }
    console.log('');
    console.log('  ' + Object.entries(tally).map(([k, v]) => `${k} ${v}`).join('、'));
    if (tally['不符'] || tally['失敗']) process.exit(1);
}
