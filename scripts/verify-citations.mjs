const normalise = text => text
    .replace(PUNCTUATION, '')
    .split('')
    .map(ch => SIMPLIFIED_TO_TRADITIONAL[ch] || ch)
    .join('');

/**
 * 語料每一行的行首帶原書自編序號（如 `41 	六儀擊刑…`）
 *
 * 引文若跨行，去標點後會把那個序號黏進正文中間，於是比對必敗——
 * 症狀是「語料下一字」變成一個阿拉伯數字。故先逐行剝除。
 */
const LINE_NUMBER_PREFIX = /^\s*\d+\s*/;

const corpusCache = new Map();
function loadCorpus(dir, file) {
    const key = `${dir}/${file}`;
    if (!corpusCache.has(key)) {
        corpusCache.set(key, existsSync(key)
            ? normalise(readFileSync(key, 'utf8')
                .split('\n')
                .map(line => line.replace(LINE_NUMBER_PREFIX, ''))
                .join(''))
            : null);
    }
    return corpusCache.get(key);
}

/**
 * 核對一條引文
 *
 * 引文中的「……」代表節略，故切成片段逐一比對——每一段都必須出現在該書中。
 * 片段短於六字者不比對（太短易誤中）。
 */
export function verifyCitation(dir, key, source) {
    if (NOT_A_SINGLE_FILE.includes(source.書)) {
        return { key, 狀態: '略過', 說明: `${source.書} 不繫於單一語料檔` };
    }
    const file = BOOK_FILES[source.書];
    if (!file) {
        return { key, 狀態: '失敗', 說明: `書名「${source.書}」不在語料檔對照表中` };
    }
    const text = loadCorpus(dir, file);
    if (text === null) {
        return { key, 狀態: '無語料', 說明: `找不到 ${file}` };
    }

    // 引文與語料有出入者（語料訛字、簡繁過度轉換、節略未標省略號），
    // 須以「校記」明文宣告，並另給「核對片段」——逐字相符的那幾段。
    // 如此仍保有實質的核對力，而非整條放行。
    if (source.核對片段) {
        if (!source.校記) {
            return { key, 狀態: '失敗', 說明: '有核對片段而無校記——出入之處必須說明' };
        }
    } else if (source.校記) {
        return { key, 狀態: '失敗', 說明: '有校記而無核對片段——宣告了出入卻無從核對' };
    }

    const fragments = (source.核對片段 || source.文.split(ELLIPSIS))
        .map(part => normalise(part))
        .filter(part => part.length >= 6);
    if (fragments.length === 0) {
        return { key, 狀態: '失敗', 說明: '引文過短或為空，無從核對' };
    }

    const missing = fragments.filter(f => !text.includes(f));
    if (missing.length === 0) {
        return {
            key,
            狀態: source.校記 ? '相符（有校記）' : '相符',
            說明: `${fragments.length} 個片段皆見於 ${file}`
                + (source.校記 ? `　校記：${source.校記.slice(0, 30)}…` : '')
        };
    }
    return {
        key,
        狀態: '不符',
        說明: `${missing.length}/${fragments.length} 個片段未見於 ${file}`,
        未命中: missing.map(f => f.slice(0, 40))
    };
}

/** 核對全部 */
export function verifyAllCitations(dir) {
    return Object.entries(SOURCES).map(([key, source]) => verifyCitation(dir, key, source));
}

